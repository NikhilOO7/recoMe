import { createLogger } from '@utils/Logger';
import { getBrain } from '@brain/BrainFacade';
import { RetrievalService, type UserContext } from '../retrieval';
import { CompareService, type CompareResult, type RankedCandidate } from '../compare';
import { WatchlistService } from '../watchlist';
import { AIChatEngine } from './AIChatEngine';
import type { CandidateEntity } from '@schema/entities';
import type { PageContext } from '@schema/decisions';
import type { IntentType } from '@schema/intent';
import type { WatchlistItem } from '@schema/watchlist';

const log = createLogger('ChatRouter');

// ── Message types ─────────────────────────────────────────────────────────

export interface AgentMessage {
  role: 'user' | 'agent';
  content: string;
  timestamp: string;
  /** Structured actions the agent suggests (open product, save watchlist, etc.) */
  actions?: AgentAction[];
  /** Ranked results if this was a compare/rank response */
  ranked?: RankedCandidate[];
  /** Follow-up suggestions from the AI */
  suggestedFollowups?: string[];
  /** Whether this response was generated by AI (true) or quick mode (false) */
  aiPowered?: boolean;
}

export interface AgentAction {
  action: 'open_product' | 'open_compare' | 'save_watchlist' | 'record_intent';
  label: string;
  targetUrl?: string;
  candidateIds?: string[];
  metadata?: Record<string, unknown>;
}

/** What the user is trying to do */
type UserIntentCategory =
  | 'compare' // compare products
  | 'recommend' // ask for recommendation
  | 'watchlist_add' // save to watchlist
  | 'watchlist_view' // view watchlist
  | 'intent_record' // declare a preference
  | 'explain' // ask why something was recommended
  | 'general'; // general question

// ── Intent detection patterns ─────────────────────────────────────────────

const INTENT_PATTERNS: Array<{ pattern: RegExp; category: UserIntentCategory }> = [
  { pattern: /\b(compare|vs|versus|differ|difference|better)\b/i, category: 'compare' },
  { pattern: /\b(recommend|suggest|best|top|which|should i)\b/i, category: 'recommend' },
  { pattern: /\b(save|watchlist|watch|track|follow|bookmark)\b/i, category: 'watchlist_add' },
  { pattern: /\b(my watchlist|saved|watching|tracked)\b/i, category: 'watchlist_view' },
  {
    pattern: /\b(already bought|one.?time|prefer|avoid|not interested|budget|quality first)\b/i,
    category: 'intent_record',
  },
  { pattern: /\b(why|explain|reason|how come)\b/i, category: 'explain' },
];

// ── Intent type extraction from natural language ──────────────────────────

const INTENT_TYPE_PATTERNS: Array<{ pattern: RegExp; intentType: IntentType }> = [
  { pattern: /\balready bought\b/i, intentType: 'already_bought' },
  { pattern: /\bone.?time\b/i, intentType: 'one_time_need' },
  { pattern: /\bprefer\b.*\bbrand\b|\bprefer\b/i, intentType: 'prefer_brand' },
  { pattern: /\bavoid\b.*\bseller\b|\bavoid\b/i, intentType: 'avoid_seller' },
  { pattern: /\bnot interested\b|\bdon'?t want\b|\bno thanks\b/i, intentType: 'not_interested' },
  { pattern: /\binterested\b|\blike\b|\bwant\b/i, intentType: 'interested' },
  { pattern: /\bresearch\b|\bjust looking\b|\bbrowsing\b/i, intentType: 'researching' },
  { pattern: /\bbudget\b|\bcheap\b|\baffordable\b/i, intentType: 'budget_sensitive' },
  { pattern: /\bquality\b|\bbest quality\b|\bpremium\b/i, intentType: 'quality_first' },
];

export class ChatRouter {
  private readonly retrieval = new RetrievalService();
  private readonly compare = new CompareService();
  private readonly watchlist = new WatchlistService();
  private readonly aiEngine = new AIChatEngine();

  /**
   * Process a user message and return an agent response.
   * If an LLM is configured, delegates to the AI chat engine for natural conversation.
   * Falls back to regex-based routing when no LLM is available.
   */
  async processMessage(
    userMessage: string,
    candidates?: CandidateEntity[],
    pageContext?: PageContext,
  ): Promise<AgentMessage> {
    // Try AI-powered chat first
    if (await this.aiEngine.isAvailable()) {
      try {
        log.info(`AI chat: "${userMessage.slice(0, 50)}"`);
        const result = await this.aiEngine.processMessage(userMessage, candidates, pageContext);
        return { ...result, aiPowered: true };
      } catch (err) {
        log.warn('AI chat failed, falling back to quick mode', err);
      }
    }

    // Fallback: regex-based routing
    return this.processMessageQuick(userMessage, candidates, pageContext);
  }

  /**
   * Regex-based message processing (quick mode).
   * Used when no LLM is configured or when AI chat fails.
   */
  private async processMessageQuick(
    userMessage: string,
    candidates?: CandidateEntity[],
    pageContext?: PageContext,
  ): Promise<AgentMessage> {
    const category = this.detectIntent(userMessage);
    log.info(`Quick mode intent: "${userMessage.slice(0, 50)}" → ${category}`);

    const userContext = await this.retrieval.getUserContext();

    switch (category) {
      case 'compare':
        return this.handleCompare(userMessage, candidates ?? [], pageContext, userContext);
      case 'recommend':
        return this.handleRecommend(userMessage, candidates ?? [], pageContext, userContext);
      case 'watchlist_add':
        return this.handleWatchlistAdd(userMessage, candidates);
      case 'watchlist_view':
        return this.handleWatchlistView();
      case 'intent_record':
        return this.handleIntentRecord(userMessage, candidates);
      case 'explain':
        return this.handleExplain(userMessage, candidates, userContext);
      case 'general':
      default:
        return this.handleGeneral(userMessage, userContext);
    }
  }

  /** Get the AI provider name for UI display. */
  async getAIProviderName(): Promise<string | null> {
    return this.aiEngine.getProviderName();
  }

  /** Check if AI chat is available. */
  async isAIPowered(): Promise<boolean> {
    return this.aiEngine.isAvailable();
  }

  // ── Intent detection ────────────────────────────────────────────────────

  private detectIntent(message: string): UserIntentCategory {
    for (const { pattern, category } of INTENT_PATTERNS) {
      if (pattern.test(message)) return category;
    }
    return 'general';
  }

  private detectIntentType(message: string): IntentType | null {
    for (const { pattern, intentType } of INTENT_TYPE_PATTERNS) {
      if (pattern.test(message)) return intentType;
    }
    return null;
  }

  // ── Handlers ────────────────────────────────────────────────────────────

  private async handleCompare(
    _message: string,
    candidates: CandidateEntity[],
    pageContext: PageContext | undefined,
    userContext: UserContext,
  ): Promise<AgentMessage> {
    if (candidates.length < 2) {
      return this.makeResponse(
        "I need at least two products to compare. Try browsing a search page and I'll compare the products you're looking at.",
      );
    }

    const ctx = pageContext ?? this.defaultPageContext();
    const result = await this.compare.compareAndRank(candidates, ctx, userContext);

    return this.formatCompareResponse(result);
  }

  private async handleRecommend(
    _message: string,
    candidates: CandidateEntity[],
    pageContext: PageContext | undefined,
    userContext: UserContext,
  ): Promise<AgentMessage> {
    if (candidates.length === 0) {
      return this.makeResponse(
        "I don't have any products to rank right now. Browse a product page or search results and I can help recommend the best option for you.",
      );
    }

    const ctx = pageContext ?? this.defaultPageContext();
    const result = await this.compare.compareAndRank(candidates, ctx, userContext);

    return this.formatRecommendResponse(result, userContext);
  }

  private async handleWatchlistAdd(
    _message: string,
    candidates?: CandidateEntity[],
  ): Promise<AgentMessage> {
    // If we have candidates, save the first one (or all)
    if (candidates && candidates.length > 0) {
      const saved: WatchlistItem[] = [];
      for (const c of candidates.slice(0, 5)) {
        const item = await this.watchlist.add({
          entityType: 'product',
          entityId: c.candidateId,
          note: c.rawText,
        });
        saved.push(item);
      }

      const names = candidates
        .slice(0, 5)
        .map((c) => c.rawText)
        .join(', ');
      return this.makeResponse(
        `Saved ${saved.length} item${saved.length > 1 ? 's' : ''} to your watchlist: ${names}`,
        saved.map((s) => ({
          action: 'save_watchlist' as const,
          label: `Saved: ${s.entityId}`,
          candidateIds: [s.entityId],
        })),
      );
    }

    return this.makeResponse(
      "I couldn't find a specific product to save. Try asking while viewing a product page.",
    );
  }

  private async handleWatchlistView(): Promise<AgentMessage> {
    const items = await this.watchlist.getAll();

    if (items.length === 0) {
      return this.makeResponse(
        'Your watchlist is empty. Save products while browsing to track them here.',
      );
    }

    const lines = items.map((item, i) => {
      const note = item.note ? ` — ${item.note}` : '';
      return `${i + 1}. ${item.entityType}: ${item.entityId}${note}`;
    });

    const actions: AgentAction[] = items.map((item) => ({
      action: 'open_product' as const,
      label: `Open ${item.entityId}`,
      candidateIds: [item.entityId],
    }));

    return this.makeResponse(
      `Your watchlist (${items.length} item${items.length > 1 ? 's' : ''}):\n${lines.join('\n')}`,
      actions,
    );
  }

  private async handleIntentRecord(
    message: string,
    candidates?: CandidateEntity[],
  ): Promise<AgentMessage> {
    const intentType = this.detectIntentType(message);
    if (!intentType) {
      return this.makeResponse(
        "I couldn't determine your preference from that. Try saying something like:\n" +
          '- "I already bought this"\n' +
          '- "I prefer Sony for headphones"\n' +
          '- "Avoid third-party sellers"\n' +
          '- "Budget sensitive right now"',
      );
    }

    // Session-scoped intents don't need an entity
    if (intentType === 'quality_first' || intentType === 'budget_sensitive') {
      const brain = getBrain();
      await brain.recordIntent('agent', 'product', 'session', intentType);
      const label = intentType === 'quality_first' ? 'Quality first' : 'Budget sensitive';
      return this.makeResponse(
        `Got it — ${label} mode is now active. This will affect your future recommendations.`,
      );
    }

    // Entity-scoped intents need a candidate
    if (!candidates || candidates.length === 0) {
      return this.makeResponse(
        `I understand you want to record "${intentType.replace(/_/g, ' ')}", but I need a product to apply it to. Try this while viewing a product page.`,
      );
    }

    const target = candidates[0]!;
    const brain = getBrain();
    const entityType =
      intentType === 'prefer_brand'
        ? 'brand'
        : intentType === 'avoid_seller'
          ? 'seller'
          : 'product';
    const entityId =
      entityType === 'brand'
        ? (target.brandId ?? target.candidateId)
        : entityType === 'seller'
          ? (target.sellerId ?? target.candidateId)
          : target.candidateId;

    await brain.recordIntent('agent', entityType, entityId, intentType);

    return this.makeResponse(
      `Recorded: "${intentType.replace(/_/g, ' ')}" for ${entityType} ${entityId}. This will affect your future recommendations.`,
    );
  }

  private async handleExplain(
    _message: string,
    candidates: CandidateEntity[] | undefined,
    userContext: UserContext,
  ): Promise<AgentMessage> {
    if (!candidates || candidates.length === 0) {
      // General explanation of user's preference state
      const parts: string[] = ["Here's what I know about your preferences:"];

      if (userContext.brandPreferences.length > 0) {
        const liked = userContext.brandPreferences.filter((b) => b.sentiment === 'positive');
        const disliked = userContext.brandPreferences.filter((b) => b.sentiment === 'negative');
        if (liked.length > 0)
          parts.push(`Preferred brands: ${liked.map((b) => b.displayName).join(', ')}`);
        if (disliked.length > 0)
          parts.push(`Avoided brands: ${disliked.map((b) => b.displayName).join(', ')}`);
      }

      if (userContext.sellerPreferences.length > 0) {
        parts.push(
          `Avoided sellers: ${userContext.sellerPreferences.map((s) => s.displayName).join(', ')}`,
        );
      }

      parts.push(`Recent intents: ${userContext.recentIntents.length}`);
      parts.push(`Watchlist items: ${userContext.watchlist.length}`);

      if (parts.length === 1) {
        parts.push(
          "I don't have much preference data yet. Use the extension to mark products and I'll learn your preferences.",
        );
      }

      return this.makeResponse(parts.join('\n'));
    }

    // Explain a specific product
    const target = candidates[0]!;
    const ctx = this.defaultPageContext();
    const result = await this.compare.compareAndRank([target], ctx, userContext);

    if (result.bestMatch) {
      const r = result.bestMatch;
      const lines = [
        `**${target.rawText}**`,
        `Decision: ${r.decision} (score: ${r.score.toFixed(2)}, confidence: ${(r.confidence * 100).toFixed(0)}%)`,
        `Reason: ${r.explanation}`,
      ];
      if (r.tradeoffs.length > 0) {
        lines.push('Factors:');
        r.tradeoffs.forEach((t) => lines.push(`  - ${t}`));
      }
      return this.makeResponse(lines.join('\n'));
    }

    return this.makeResponse("I don't have enough data to explain this product's ranking yet.");
  }

  private async handleGeneral(_message: string, userContext: UserContext): Promise<AgentMessage> {
    const parts: string[] = [
      "I'm your shopping companion. Here's what I can help with:",
      '',
      '- **Compare** products: "Compare these headphones"',
      '- **Recommend** the best option: "Which should I buy?"',
      '- **Save** to watchlist: "Save this for later"',
      '- **Declare preferences**: "I already bought this" or "I prefer Sony"',
      '- **Explain** rankings: "Why was this recommended?"',
      '- **View watchlist**: "Show my watchlist"',
    ];

    if (userContext.recentIntents.length > 0) {
      parts.push('');
      parts.push(
        `I have ${userContext.recentIntents.length} preference signals and ${userContext.watchlist.length} watchlist items to work with.`,
      );
    }

    return this.makeResponse(parts.join('\n'));
  }

  // ── Response formatting ─────────────────────────────────────────────────

  private formatCompareResponse(result: CompareResult): AgentMessage {
    const lines: string[] = [];

    if (result.bestMatch) {
      const best = result.bestMatch;
      const title = best.metadata['brand']
        ? `${best.metadata['brand']} — ${best.candidateId}`
        : best.candidateId;
      lines.push(`**Best match:** ${title}`);
      lines.push(`Why: ${best.explanation}`);

      if (best.tradeoffs.length > 0) {
        best.tradeoffs.forEach((t) => lines.push(`  + ${t}`));
      }
    }

    if (result.alternatives.length > 0) {
      lines.push('');
      lines.push('**Alternatives:**');
      for (const alt of result.alternatives.slice(0, 4)) {
        const title = alt.metadata['brand']
          ? `${alt.metadata['brand']} — ${alt.candidateId}`
          : alt.candidateId;
        const price = alt.metadata['price'] as number | undefined;
        const priceStr = price !== undefined ? ` ($${price.toFixed(2)})` : '';
        lines.push(`${alt.rank}. ${title}${priceStr} — ${alt.decision}`);
        if (alt.tradeoffs.length > 0) {
          lines.push(`   ${alt.tradeoffs[0]}`);
        }
      }
    }

    const actions: AgentAction[] = result.ranked.map((r) => ({
      action: 'open_product' as const,
      label: `Open #${r.rank}`,
      candidateIds: [r.candidateId],
      metadata: { url: r.metadata['url'] },
    }));

    return {
      role: 'agent',
      content: lines.join('\n'),
      timestamp: new Date().toISOString(),
      actions,
      ranked: result.ranked,
    };
  }

  private formatRecommendResponse(result: CompareResult, userContext: UserContext): AgentMessage {
    const lines: string[] = [];

    if (!result.bestMatch) {
      return this.makeResponse('No strong recommendation — not enough preference data yet.');
    }

    const best = result.bestMatch;
    const title = best.metadata['brand']
      ? `${best.metadata['brand']} product`
      : `Product ${best.candidateId}`;

    lines.push(`**Recommended: ${title}**`);
    lines.push(best.explanation);

    // Mention preference basis
    const preferred = userContext.brandPreferences.filter((b) => b.sentiment === 'positive');
    if (preferred.length > 0) {
      lines.push(`Based on your preference for: ${preferred.map((b) => b.displayName).join(', ')}`);
    }

    if (result.alternatives.length > 0) {
      lines.push('');
      lines.push(
        `${result.alternatives.length} other option${result.alternatives.length > 1 ? 's' : ''} available.`,
      );
    }

    lines.push('');
    lines.push('Next: Save to watchlist or open product page?');

    const actions: AgentAction[] = [
      {
        action: 'open_product',
        label: 'Open product',
        candidateIds: [best.candidateId],
        metadata: { url: best.metadata['url'] },
      },
      { action: 'save_watchlist', label: 'Save to watchlist', candidateIds: [best.candidateId] },
    ];

    return {
      role: 'agent',
      content: lines.join('\n'),
      timestamp: new Date().toISOString(),
      actions,
      ranked: result.ranked,
    };
  }

  private makeResponse(content: string, actions?: AgentAction[]): AgentMessage {
    return {
      role: 'agent',
      content,
      timestamp: new Date().toISOString(),
      actions,
    };
  }

  private defaultPageContext(): PageContext {
    return {
      site: 'unknown',
      pageType: 'unknown',
      url: '',
      timestamp: new Date().toISOString(),
    };
  }
}
